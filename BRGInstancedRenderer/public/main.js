// Inject GoatCounter analytics tag on every page.
// Privacy-friendly, cookie-free, GDPR-compliant analytics.
(function () {
  var s = document.createElement('script');
  s.src = 'https://gc.zgo.at/count.js';
  s.async = true;
  s.setAttribute('data-goatcounter', 'https://milk-drinker01.goatcounter.com/count');
  document.head.appendChild(s);
})();
